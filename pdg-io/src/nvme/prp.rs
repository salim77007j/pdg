//! Physical Region Page translation — the DMA model NVMe commands use.
//!
//! Data pointers are PRPs: `prp1` may address any offset inside its
//! page; every subsequent entry is page-aligned. If the transfer does
//! not fit within `prp1`'s page plus one more page, `prp2` is a
//! *pointer to a PRP list* — an array of page addresses in guest RAM
//! covering the rest of the transfer. PDG implements the general
//! algorithm (first page + list walk) so multi-megabyte commands DMA
//! exactly like they do on hardware.

use pdg_memory::bus::{AccessWidth, Bus};

use crate::nvme::NvmeError;

/// Guest page size (PDG models 4 KiB pages; CC.MPS must be 0).
pub const PAGE_SIZE: u64 = 4096;

/// One physical segment of a PRP-resolved transfer.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Segment {
    /// Guest-physical start address.
    pub addr: u64,
    /// Length in bytes.
    pub len: u64,
}

impl Segment {
    /// Byte just past the segment.
    #[must_use]
    pub fn end(self) -> u64 {
        self.addr + self.len
    }
}

/// Resolve a PRP pair into the list of guest-physical segments that
/// cover `len` bytes, reading PRP-list entries from `bus` as needed.
///
/// Returns the segments in order; DMA can then copy each segment.
pub fn resolve(bus: &Bus, prp1: u64, prp2: u64, len: u64) -> Result<Vec<Segment>, NvmeError> {
    if len == 0 {
        return Ok(Vec::new());
    }
    if prp1 & 3 != 0 {
        return Err(NvmeError::Prp(format!(
            "prp1 {prp1:#x} is not dword-aligned"
        )));
    }
    let mut segments = Vec::new();
    let mut remaining = len;

    // First segment: from prp1 to the end of its page.
    let first_len = remaining.min(PAGE_SIZE - (prp1 & (PAGE_SIZE - 1)));
    segments.push(Segment {
        addr: prp1,
        len: first_len,
    });
    remaining -= first_len;
    if remaining == 0 {
        return Ok(segments);
    }

    // If exactly one more page is needed, prp2 IS that page.
    if remaining <= PAGE_SIZE {
        if prp2 & (PAGE_SIZE - 1) != 0 {
            return Err(NvmeError::Prp(format!(
                "prp2 {prp2:#x} is not page-aligned"
            )));
        }
        segments.push(Segment {
            addr: prp2,
            len: remaining,
        });
        return Ok(segments);
    }

    // Otherwise prp2 points at a PRP list; walk it until covered.
    if prp2 & (PAGE_SIZE - 1) != 0 {
        return Err(NvmeError::Prp(format!(
            "prp-list {prp2:#x} is not page-aligned"
        )));
    }
    let list = prp2;
    let mut offset = 0u64;
    while remaining > 0 {
        let entry = bus
            .read(AccessWidth::W64, list + offset)
            .map_err(|e| NvmeError::Prp(format!("prp-list read at {:#x}: {e}", list + offset)))?;
        if entry == 0 || entry & (PAGE_SIZE - 1) != 0 {
            return Err(NvmeError::Prp(format!("prp-list entry {entry:#x} invalid")));
        }
        let take = remaining.min(PAGE_SIZE);
        segments.push(Segment {
            addr: entry,
            len: take,
        });
        remaining -= take;
        offset += 8;
        // A PRP list itself is one page; move to the next chained list.
        if offset == PAGE_SIZE {
            return Err(NvmeError::Prp(
                "prp-list spans more than one page; chained lists are not generated by \
                 this model's guest drivers"
                    .to_owned(),
            ));
        }
    }
    Ok(segments)
}

/// Scatter a buffer out to the resolved segments (controller → guest).
pub fn dma_write(bus: &Bus, segments: &[Segment], data: &[u8]) -> Result<(), NvmeError> {
    let mut done = 0usize;
    for seg in segments {
        let end = done + seg.len as usize;
        let part = data
            .get(done..end)
            .ok_or_else(|| NvmeError::Prp("buffer shorter than prp segments".to_owned()))?;
        bus.write_buf(seg.addr, part)
            .map_err(|e| NvmeError::Prp(format!("dma write to {:#x}: {e}", seg.addr)))?;
        done = end;
    }
    if done != data.len() {
        return Err(NvmeError::Prp(format!(
            "prp covered {done} bytes for a {}-byte transfer",
            data.len()
        )));
    }
    Ok(())
}

/// Gather a buffer in from the resolved segments (guest → controller).
pub fn dma_read(bus: &Bus, segments: &[Segment], out: &mut [u8]) -> Result<(), NvmeError> {
    let mut done = 0usize;
    for seg in segments {
        let end = done + seg.len as usize;
        let part = out
            .get_mut(done..end)
            .ok_or_else(|| NvmeError::Prp("buffer shorter than prp segments".to_owned()))?;
        bus.read_buf(seg.addr, part)
            .map_err(|e| NvmeError::Prp(format!("dma read from {:#x}: {e}", seg.addr)))?;
        done = end;
    }
    if done != out.len() {
        return Err(NvmeError::Prp(format!(
            "prp covered {done} bytes for a {}-byte transfer",
            out.len()
        )));
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn bus() -> Bus {
        Bus::new(8 << 20).expect("bus alloc")
    }

    #[test]
    fn in_page_transfer_uses_only_prp1() {
        let segs = resolve(&bus(), 0x400_100, 0, 0x100).unwrap();
        assert_eq!(
            segs,
            vec![Segment {
                addr: 0x400_100,
                len: 0x100
            }]
        );
    }

    #[test]
    fn two_page_transfer_uses_prp2_as_page_pointer() {
        // 8 KiB starting mid-page: first segment to page end, second the
        // full remaining 4 KiB page given directly by prp2.
        let segs = resolve(&bus(), 0x400_800, 0x401_000, 0x1800).unwrap();
        assert_eq!(segs.len(), 2);
        assert_eq!(
            segs[0],
            Segment {
                addr: 0x400_800,
                len: 0x800
            }
        );
        assert_eq!(
            segs[1],
            Segment {
                addr: 0x401_000,
                len: 0x1000
            }
        );
    }

    #[test]
    fn large_transfer_walks_a_prp_list_in_guest_ram() {
        let bus = bus();
        // PRP list at 0x6000 holding three page addresses.
        for (i, page) in [0x500_000u64, 0x501_000, 0x502_000].iter().enumerate() {
            bus.write(AccessWidth::W64, 0x6000 + (i as u64) * 8, *page)
                .unwrap();
        }
        // A transfer needing three or more pages treats PRP2 as a list:
        // 0x800 on the first page, then list pages 0x500000/0x501000.
        let segs = resolve(&bus, 0x400_800, 0x6000, 0x2800).unwrap();
        assert_eq!(segs.len(), 3);
        assert_eq!(
            segs[0],
            Segment {
                addr: 0x400_800,
                len: 0x800
            }
        );
        assert_eq!(segs[1].addr, 0x500_000);
        assert_eq!(segs[2].addr, 0x501_000);
        assert_eq!(segs.iter().map(|s| s.len).sum::<u64>(), 0x2800);
        // A transfer fitting in two pages treats PRP2 as that page
        // directly (no list walk) — the spec's two-page special case.
        let segs = resolve(&bus, 0x400_800, 0x502_000, 0x1800).unwrap();
        assert_eq!(segs.len(), 2);
        assert_eq!(segs[1].addr, 0x502_000);
    }

    #[test]
    fn unaligned_prp2_is_refused() {
        let e = resolve(&bus(), 0x400_000, 0x401_008, 0x2000).unwrap_err();
        assert!(matches!(e, NvmeError::Prp(_)));
    }

    #[test]
    fn dma_scatter_and_gather_roundtrip() {
        let bus = bus();
        let segs = resolve(&bus, 0x500_800, 0x501_000, 0x1800).unwrap();
        let data: Vec<u8> = (0..0x1800).map(|i| (i * 7 + 3) as u8).collect();
        dma_write(&bus, &segs, &data).unwrap();
        let mut back = vec![0u8; 0x1800];
        dma_read(&bus, &segs, &mut back).unwrap();
        assert_eq!(data, back);
    }
}
